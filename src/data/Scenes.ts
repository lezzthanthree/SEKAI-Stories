export const CheckSceneCategory = (blank: boolean): string => {
    if (blank) return "blank";

    const date = new Date();
    const [month, day] = [date.getMonth() + 1, date.getDate()];

    const exact: Record<string, string> = {
        "3-5": "memories-of-you",
        "3-9": "sankyuu",
        "7-27": "727",
        "8-27": "mizuki",
        "8-31": "mikudayo",
        "10-3": "nomizu5",
    };

    if (exact[`${month}-${day}`]) return exact[`${month}-${day}`];

    const range: Array<[number, number, number, string]> = [
        [2, 13, 19, "valentine"],
        [4, 10, 18, "pre-anniversary"],
        [4, 19, 30, "anniversary-event"],
    ];

    for (const [m, start, end, value] of range) {
        if (month === m && day >= start && day <= end) return value;
    }

    const months: Record<number, string> = {
        10: "halloween",
        // 12: "christmas", # TODO
    };

    if (month in months) return months[month];

    return "default";
};
